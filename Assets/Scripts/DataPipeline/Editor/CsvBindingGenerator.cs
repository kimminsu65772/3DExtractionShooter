using System;
using System.Reflection;
using System.Collections.Generic;
using System.Text;
using System.IO;
using System.Threading;
using System.Threading.Tasks;
using UnityEngine;

namespace ExtractionShooter.DataPipeline
{
    // Editor 폴더: 생성 시에만 reflection 사용. 런타임 DLL에 포함시키지 않는다.
    public static class CsvBindingGenerator
    {
        [UnityEditor.MenuItem("Tools/CSV/Preview Weapon Binding")]
        private static void PreviewWeaponBinding()
        {
            string generatedCode = Generate(typeof(WeaponDefinition));
            UnityEngine.Debug.Log(generatedCode);
        }

        public static string Generate(Type modelType)
        {
            // 모델 타입의 public instance field를 가져온다. 
            FieldInfo[] fields = modelType.GetFields(BindingFlags.Public | BindingFlags.Instance);

            Array.Sort(fields, (left, right) => StringComparer.Ordinal.Compare(left.Name, right.Name));

            HashSet<string> columnNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            StringBuilder builder = new StringBuilder();
            StringBuilder bindingBody = new StringBuilder();

            string modelName = modelType.Name;

            // 모델 이름이 "Definition"으로 끝나면 제거한다. (예: "EnemyDefinition" -> "Enemy")
            if (modelName.EndsWith("Definition", StringComparison.Ordinal))
            {
                modelName = modelName.Substring(0, modelName.Length - "Definition".Length);
            }

            string className = $"Generated{modelName}Binding";

            string modelTypeName = $"global::{modelType.FullName.Replace('+', '.')}";
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Collections.Generic;");
            builder.AppendLine();
            builder.AppendLine("namespace ExtractionShooter.DataPipeline");
            builder.AppendLine("{");
            builder.AppendLine($"    public sealed class {className} : ICsvBinding<{modelTypeName}>");
            builder.AppendLine("    {");
            builder.AppendLine("        public IReadOnlyList<string> ExpectedHeaders { get; } =");
            builder.AppendLine("            new string[]");
            builder.AppendLine("            {");
            foreach (FieldInfo field in fields)
            {
                // 필드가 읽기 전용이면 건너뛴다.
                if (field.IsInitOnly)
                    continue;
                // 필드가 NonSerializedAttribute 또는 CsvIgnoreAttribute로 표시되어 있으면 건너뛴다.
                if (field.IsDefined(typeof(NonSerializedAttribute), false))
                    continue;
                if (field.IsDefined(typeof(CsvIgnoreAttribute), false))
                    continue;

                // 필드에 CsvColumnAttribute가 있는지 확인하고, 있으면 해당 속성을 가져온다.
                CsvColumnAttribute columnAttribute = field.GetCustomAttribute<CsvColumnAttribute>();

                // CsvColumnAttribute의 Name 속성이 비어있으면 필드 이름을, 그렇지 않으면 Name 속성을 사용하여 컬럼 이름을 결정한다. 
                string columnName =
                    string.IsNullOrWhiteSpace(columnAttribute?.Name)
                    ? field.Name
                    : columnAttribute.Name;

                if (!columnNames.Add(columnName))
                {
                    throw new InvalidOperationException(
                        $"{modelType.Name}: CSV 열 이름이 중복됩니다. ({columnName})");
                }

                // 해당 열이 선택 항목에 해당하는지 확인한다. (생략 여부 판단용)
                bool isOptional = columnAttribute?.Optional ?? false;

                // 타입 변환기에서 처리할 수 있는 타입인지 확인한다. 지원되지 않는 타입이면 예외를 발생시킨다.
                Type fieldType = field.FieldType;

                bool isSupported =
                    fieldType == typeof(int) ||
                    fieldType == typeof(float) ||
                    fieldType == typeof(string) ||
                    fieldType.IsEnum;

                if (!isSupported)
                {
                    throw new NotSupportedException(
                        $"{modelType.Name}.{field.Name}: " +
                        $"지원하지 않는 필드 타입입니다. ({fieldType.Name})");
                }

                bindingBody.AppendLine($"            // {field.Name} 필드의 CSV 값을 읽고 변환한다.");

                string escapedColumnName = columnName.Replace("\"", "\"\"");

                builder.AppendLine($"                @\"{escapedColumnName}\",");
                bindingBody.AppendLine("            {");
                bindingBody.AppendLine($"                bool hasColumn = header.TryGetValue(@\"{escapedColumnName}\", out int columnIndex);");
                bindingBody.AppendLine("                if (!hasColumn)");
                bindingBody.AppendLine("                {");

                if (!isOptional)
                {
                    bindingBody.AppendLine("                    isValid = false;");
                    bindingBody.AppendLine("                    report.Add(new DataIssue");
                    bindingBody.AppendLine("                    {");
                    bindingBody.AppendLine("                        Record = row.Number,");
                    bindingBody.AppendLine(
                        $"                        Column = @\"{escapedColumnName}\",");
                    bindingBody.AppendLine(
                        "                        Message = \"필수 열이 없습니다.\"");
                    bindingBody.AppendLine("                    });");
                }

                bindingBody.AppendLine("                }");
                bindingBody.AppendLine("                else");
                bindingBody.AppendLine("                {");
                bindingBody.AppendLine(
                    "                    if (columnIndex < 0 || columnIndex >= row.Cells.Length)");
                bindingBody.AppendLine("                    {");
                bindingBody.AppendLine("                        isValid = false;");
                bindingBody.AppendLine("                        report.Add(new DataIssue");
                bindingBody.AppendLine("                        {");
                bindingBody.AppendLine("                            Record = row.Number,");
                bindingBody.AppendLine(
                    $"                            Column = @\"{escapedColumnName}\",");
                bindingBody.AppendLine(
                    "                            Message = \"열에 대응하는 셀이 없습니다.\"");
                bindingBody.AppendLine("                        });");
                bindingBody.AppendLine("                    }");
                bindingBody.AppendLine("                    else");
                bindingBody.AppendLine("                    {");
                bindingBody.AppendLine(
                    "                        string raw = row.Cells[columnIndex];");
                AppendFieldBindingCode(
                    bindingBody,
                    field,
                    fieldType,
                    escapedColumnName,
                    isOptional);
                bindingBody.AppendLine("                    }");
                bindingBody.AppendLine("                }");
                bindingBody.AppendLine("            }");
            }
            builder.AppendLine("            };");
            builder.AppendLine();
            builder.AppendLine(
                "        public bool TryBind(CsvRecord row, " +
                "IReadOnlyDictionary<string, int> header, " +
                $"DataReport report, out {modelTypeName} result)");
            builder.AppendLine("        {");
            builder.AppendLine("            result = null;");
            builder.AppendLine($"            var candidate = new {modelTypeName}();");
            builder.AppendLine("            bool isValid = true;");
            builder.Append(bindingBody.ToString());
            builder.AppendLine("            if (!isValid)");
            builder.AppendLine("                return false;");
            builder.AppendLine();
            builder.AppendLine("            result = candidate;");
            builder.AppendLine("            return true;");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static void AppendFieldBindingCode(
            StringBuilder bindingBody,
            FieldInfo field,
            Type fieldType,
            string escapedColumnName,
            bool isOptional)
        {
            if (isOptional)
            {
                bindingBody.AppendLine("                        if (string.IsNullOrWhiteSpace(raw))");
                bindingBody.AppendLine("                        {");
                bindingBody.AppendLine("                            // Optional 값이 비어 있으면 모델의 기본값을 유지한다.");
                bindingBody.AppendLine("                        }");
                bindingBody.AppendLine("                        else");
                bindingBody.AppendLine("                        {");
                AppendConversionBlock(bindingBody, field, fieldType, escapedColumnName, 7);
                bindingBody.AppendLine("                        }");
                return;
            }

            bindingBody.AppendLine("                        if (string.IsNullOrWhiteSpace(raw))");
            bindingBody.AppendLine("                        {");
            bindingBody.AppendLine("                            isValid = false;");
            AppendReportIssue(
                bindingBody,
                escapedColumnName,
                "raw",
                "필수 값이 비어 있습니다.",
                7);
            bindingBody.AppendLine("                        }");
            bindingBody.AppendLine("                        else");
            bindingBody.AppendLine("                        {");
            AppendConversionBlock(bindingBody, field, fieldType, escapedColumnName, 7);
            bindingBody.AppendLine("                        }");
        }

        private static void AppendConversionBlock(
            StringBuilder bindingBody,
            FieldInfo field,
            Type fieldType,
            string escapedColumnName,
            int indentLevel)
        {
            string indent = new string(' ', indentLevel * 4);
            string fieldName = field.Name;

            if (fieldType == typeof(string))
            {
                bindingBody.AppendLine($"{indent}candidate.{fieldName} = raw;");
                return;
            }

            string parsedVariableName = $"{fieldName}Value";

            if (fieldType == typeof(int))
            {
                bindingBody.AppendLine($"{indent}if (!CsvValueConverter.TryInt(raw, out int {parsedVariableName}))");
            }
            else if (fieldType == typeof(float))
            {
                bindingBody.AppendLine($"{indent}if (!CsvValueConverter.TryFloat(raw, out float {parsedVariableName}))");
            }
            else if (fieldType.IsEnum)
            {
                string enumTypeName = GetGeneratedTypeName(fieldType);
                bindingBody.AppendLine($"{indent}if (!CsvValueConverter.TryEnum<{enumTypeName}>(raw, out {enumTypeName} {parsedVariableName}))");
            }
            else
            {
                throw new NotSupportedException(
                    $"{field.DeclaringType?.Name}.{field.Name}: " +
                    $"지원하지 않는 필드 타입입니다. ({fieldType.Name})");
            }

            bindingBody.AppendLine($"{indent}{{");
            bindingBody.AppendLine($"{indent}    isValid = false;");
            AppendReportIssue(
                bindingBody,
                escapedColumnName,
                "raw",
                $"값을 {GetReadableTypeName(fieldType)} 타입으로 변환할 수 없습니다.",
                indentLevel + 1);
            bindingBody.AppendLine($"{indent}}}");
            bindingBody.AppendLine($"{indent}else");
            bindingBody.AppendLine($"{indent}{{");
            bindingBody.AppendLine($"{indent}    candidate.{fieldName} = {parsedVariableName};");
            bindingBody.AppendLine($"{indent}}}");
        }

        private static void AppendReportIssue(
            StringBuilder bindingBody,
            string escapedColumnName,
            string rawValueExpression,
            string message,
            int indentLevel)
        {
            string indent = new string(' ', indentLevel * 4);

            bindingBody.AppendLine($"{indent}report.Add(new DataIssue");
            bindingBody.AppendLine($"{indent}{{");
            bindingBody.AppendLine($"{indent}    Record = row.Number,");
            bindingBody.AppendLine($"{indent}    Column = @\"{escapedColumnName}\",");
            bindingBody.AppendLine($"{indent}    RawValue = {rawValueExpression},");
            bindingBody.AppendLine($"{indent}    Message = \"{message}\"");
            bindingBody.AppendLine($"{indent}}});");
        }

        private static string GetGeneratedTypeName(Type type)
        {
            return $"global::{type.FullName.Replace('+', '.')}";
        }

        private static string GetReadableTypeName(Type type)
        {
            if (type == typeof(int))
                return "int";

            if (type == typeof(float))
                return "float";

            if (type == typeof(string))
                return "string";

            if (type.IsEnum)
                return type.Name;

            return type.Name;
        }

        public static void WriteIfChanged(Type modelType, string destination)
        {
            if (modelType == null)
                throw new ArgumentNullException(nameof(modelType));

            if (string.IsNullOrWhiteSpace(destination))
                throw new ArgumentException("생성 파일 경로가 비어 있습니다.", nameof(destination));

            // 생성된 코드를 가져오고, 줄바꿈을 통일하여 비교한다.
            string generatedCode = Generate(modelType);
            string normalizedGeneratedCode = NormalizeLineEndings(generatedCode);

            string normalizedExistingCode = string.Empty;

            // 먼저 기존 파일이 존재하는지 확인하고, 존재하면 내용을 읽어와서 줄바꿈을 통일한다.
            if (File.Exists(destination))
            {
                string existingCode = File.ReadAllText(destination);
                normalizedExistingCode = NormalizeLineEndings(existingCode);
            }

            // 기존 코드와 생성된 코드를 비교하여 동일하면 파일 쓰기를 건너뛴다.
            if (normalizedExistingCode == normalizedGeneratedCode)
            {
                Debug.Log($"[{nameof(CsvBindingGenerator)}] No changes detected for {modelType.Name}. Skipping write to {destination}.");
                return;
            }

            // 기존 코드와 생성된 코드가 다르면, 파일을 쓰기 전에 디렉토리가 존재하는지 확인하고, 없으면 생성한다.
            string directory = Path.GetDirectoryName(destination);

            if (!string.IsNullOrEmpty(directory))
            {
                Directory.CreateDirectory(directory);
            }

            // 목표 파일에 생성된 코드를 작성한다.
            File.WriteAllText(destination, generatedCode);

            // Unity 에디터에 해당 파일을 임포트한다.
            string unityPath = destination.Replace("\\", "/");
            UnityEditor.AssetDatabase.ImportAsset(unityPath);

            Debug.Log($"[{nameof(CsvBindingGenerator)}] Generated code for {modelType.Name} written to {destination}.");
        }
        public static void ValidateGeneratedCode(Type modelType, string destination)
        {
            if (modelType == null)
                throw new ArgumentNullException(nameof(modelType));

            if (string.IsNullOrWhiteSpace(destination))
                throw new ArgumentException("검증할 생성 파일 경로가 비어 있습니다.", nameof(destination));

            if (!File.Exists(destination))
            {
                throw new UnityEditor.Build.BuildFailedException(
                    $"CSV binding file is missing: {destination}");
            }

            // 코드를 생성해보고 기존 파일과 비교하여 동일하지 않으면 예외를 발생시킨다.
            string generatedCode = Generate(modelType);
            string existingCode = File.ReadAllText(destination);

            string normalizedGeneratedCode = NormalizeLineEndings(generatedCode);
            string normalizedExistingCode = NormalizeLineEndings(existingCode);

            if (normalizedGeneratedCode != normalizedExistingCode)
            {
                throw new UnityEditor.Build.BuildFailedException(
                    $"CSV binding file is outdated: {destination}. Please regenerate the binding code.");
            }

            Debug.Log($"[{nameof(CsvBindingGenerator)}] Generated binding is valid: {destination}");
        }

        private static string NormalizeLineEndings(string text)
        {
            return (text ?? string.Empty)
                .Replace("\r\n", "\n")
                .Replace("\r", "\n");
        }

        private const string WeaponBindingDestination = "Assets/Scripts/DataPipeline/Csv/GeneratedWeaponBinding.cs";

        [UnityEditor.MenuItem("Tools/CSV/Generate Weapon Binding")]

        private static void GenerateWeaponBinding()
        {
            WriteIfChanged(typeof(WeaponDefinition), WeaponBindingDestination);
        }

        [UnityEditor.MenuItem("Tools/CSV/Validate Weapon Binding")]
        private static void ValidateWeaponBinding()
        {
            ValidateGeneratedCode(typeof(WeaponDefinition), WeaponBindingDestination);
        }
    }
